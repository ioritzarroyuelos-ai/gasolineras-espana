import { expect, test } from '@playwright/test'

test('ITV: Madrid municipio aparece primero y el teclado permite elegir la provincia', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 740 })
  await page.goto('/itv/')
  const campo = page.getByRole('combobox', { name: 'Buscar municipio o provincia' })
  await campo.fill('Madrid')
  const opciones = page.getByRole('listbox', { name: 'Sugerencias' }).getByRole('option')
  await expect(opciones.nth(0)).toContainText('Madrid · Municipio')
  await expect(opciones.nth(1)).toContainText('Provincia')
  await campo.press('ArrowDown')
  await campo.press('ArrowDown')
  await expect(opciones.nth(1)).toHaveAttribute('aria-selected', 'true')
  await expect(opciones.nth(0)).toHaveAttribute('aria-selected', 'false')
  await expect(campo).toHaveAttribute('aria-activedescendant', (await opciones.nth(1).getAttribute('id'))!)
  await campo.press('Enter')
  await expect(page).toHaveURL(/\/itv\/madrid$/)
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('ITV en Madrid')
})

test('ITV: Durango muestra centros localizados ordenados por distancia en línea recta', async ({ page }) => {
  await page.goto('/itv/')
  const campo = page.getByRole('combobox', { name: 'Buscar municipio o provincia' })
  await campo.fill('Durango')
  await campo.press('Enter')
  await expect(page).toHaveURL(/\/itv\/bizkaia\/durango$/)
  await expect(page.getByRole('heading', { level: 1 })).toContainText('Durango')
  await expect(page.getByRole('heading', { name: 'Estaciones cercanas' })).toBeVisible()
  await expect(page.getByText(/Distancias en línea recta desde el centro de Durango/)).toBeVisible()
  const distancias = await page.locator('.distancia').allTextContents()
  expect(distancias.length).toBeGreaterThan(0)
  expect(distancias.length).toBeLessThanOrEqual(5)
  const valores = distancias.map(texto => Number(texto.match(/A ([\d.,]+) km/)![1].replaceAll('.', '').replace(',', '.')))
  expect(valores).toEqual([...valores].sort((a, b) => a - b))
  expect(valores.every(km => km <= 80)).toBe(true)
  expect(await page.getByRole('link', { name: 'Cómo llegar', exact: true }).count()).toBe(distancias.length)
})

test('ITV: un fallo temporal ofrece reintento y no afirma que el pueblo carece de ITV', async ({ page }, info) => {
  test.skip(info.config.metadata.live === true, 'El fallo de red se simula sólo en pruebas locales.')
  let consultas = 0
  await page.route('**/api/itv/municipios?q=*', route => {
    consultas++
    if (consultas === 1) return route.fulfill({ status: 503, json: { error: 'Temporal' } })
    return route.continue()
  })
  await page.goto('/itv/')
  const campo = page.getByRole('combobox', { name: 'Buscar municipio o provincia' })
  await campo.fill('Madrid')
  await expect(page.getByRole('alert')).toContainText('No se pudo consultar')
  expect(consultas).toBe(1)
  await expect(page.getByText('No hay coincidencias.', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Reintentar' }).click()
  await expect(page.getByRole('option').nth(0)).toContainText('Madrid · Municipio')
  expect(consultas).toBe(2)
  await expect(page.getByRole('alert')).toBeHidden()
  await campo.press('Escape')
  await expect(campo).toHaveAttribute('aria-expanded', 'false')
  await expect(campo).not.toHaveAttribute('aria-activedescendant', /.+/)
})

test.describe('ITV sin JavaScript', () => {
  test.use({ javaScriptEnabled: false })
  test('envía Madrid al municipio y ofrece las dos provincias de Cabanes', async ({ page }) => {
    await page.goto('/itv/')
    const campo = page.getByRole('searchbox', { name: 'Buscar municipio o provincia' })
    await campo.fill('Madrid')
    await campo.press('Enter')
    await expect(page).toHaveURL(/\/itv\/madrid\/madrid$/)
    await expect(page.getByRole('heading', { level: 1 })).toHaveText('ITV en Madrid')
    await campo.fill('Cabanes')
    await campo.press('Enter')
    await expect(page).toHaveURL(/\/itv\/buscar\?q=Cabanes$/)
    const resultados = page.getByRole('main')
    await expect(resultados.getByRole('link', { name: /Cabanes.*Castellón/ })).toHaveAttribute('href', '/itv/castellon/cabanes')
    await expect(resultados.getByRole('link', { name: /Cabanes.*Girona/ })).toHaveAttribute('href', '/itv/girona/cabanes')
  })
})
